def messages_for(
    product: Product, feedback: list[str] | None = None, previous: str | None = None
) -> list[dict[str, str]]:

    schema = json.dumps(Card.model_json_schema(), ensure_ascii=False)
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT + "\nJSON Schema\n" + schema},
        {
            "role": "user",
            "content": json.dumps(
                {"product": product.model_dump()}, ensure_ascii=False
            ),
        },
    ]
    if feedback:
        if previous:
            messages.append({"role": "assistant", "content": previous[:16000]})
        messages.append(
            {
                "role": "user",
                "content": json.dumps(
                    {
                        "task": "Исправь перечисленные ошибки и верни полный JSON карточки",
                        "validation_errors": feedback[:10],
                    },
                    ensure_ascii=False,
                ),
            }
        )
    return messages
